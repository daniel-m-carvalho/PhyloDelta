"""Every cell of TABLES.md that a re-run changed: old, new.

    git show <old>:code/bench/results/TABLES.md > old.md
    python3 harness/rerun_ledger.py old.md results/TABLES.md > results/RERUN_LEDGER.md

Machine-made so that the list of changes is not itself hand-copied. Cells are
matched by table number, first column and column heading. A heading or a row in
only one of the two files is listed as such rather than guessed at.
"""
import re
import sys
from pathlib import Path

HEAD = re.compile(r"^#{2,3} Table (\d+)\b")
#: Columns renamed in the re-run: the same quantity under a clearer heading.
RENAMED = {
    "PhyloDelta": "PhyloDelta, median of 6",
    "time to failure": "time",
    "build at 2 threads": "(a) `rf`, 2 threads",
    "build at 10 threads": "(a) `rf`, 10 threads",
}


def row_key(cell):
    """17,645 †, 17645 and **17,645** are one row."""
    bare = clean(cell).replace("†", "").strip()
    return bare.replace(",", "") if bare.replace(",", "").isdigit() else bare


def clean(cell):
    return cell.replace("**", "").replace("*", "").strip()


def unique(headers):
    """Table 16 has four columns called `of which fetch`; number the repeats."""
    seen, out = {}, []
    for h in headers:
        seen[h] = seen.get(h, 0) + 1
        out.append(h if seen[h] == 1 else f"{h} #{seen[h]}")
    return out


def same(a, b):
    a, b = clean(a), clean(b)
    return a == b or a.replace(",", "") == b.replace(",", "")


def tables(path):
    """{table number: [(headers, {row key: row})]}"""
    out, number, header = {}, None, None
    for line in Path(path).read_text().splitlines():
        found = HEAD.match(line)
        if found:
            number = int(found[1])
            out.setdefault(number, [])
            header = None
            continue
        if number is None:
            continue
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                continue
            if header is None:
                header = unique([RENAMED.get(clean(c), c) for c in cells])
                out[number].append((header, {}))
            elif len(cells) == len(header):
                out[number][-1][1][row_key(cells[0])] = dict(zip(header, cells, strict=True))
        else:
            header = None
    return out


def main():
    old, new = tables(sys.argv[1]), tables(sys.argv[2])
    print("# Every table cell that changed in the re-run\n")
    print("Generated by `harness/rerun_ledger.py` from the `TABLES.md` before the re-run and the "
          "one regenerated from it. Reasons are in `RERUN_REPORT.md`, which names the DECISIONS "
          "section that records them.\n")
    for number in sorted(set(old) | set(new)):
        before, after = old.get(number, []), new.get(number, [])
        lines = []
        for index, (headers, rows) in enumerate(after):
            if index >= len(before):
                lines.append(f"*A table that did not exist before: {' / '.join(headers[:4])} …, {len(rows)} rows.*")
                continue
            old_headers, old_rows = before[index]
            gone = [h for h in old_headers if h not in headers]
            came = [h for h in headers if h not in old_headers]
            if gone:
                lines.append("*Columns removed: " + ", ".join(f"`{clean(h)}`" for h in gone) + ".*")
            if came:
                lines.append("*Columns added: " + ", ".join(f"`{clean(h)}`" for h in came) + ".*")
            for key, row in rows.items():
                if key not in old_rows:
                    lines.append(f"*Row added: {key}.*")
                    continue
                for h in headers:
                    if h in old_rows[key] and not same(old_rows[key][h], row[h]):
                        lines.append(f"| {key} | {clean(h)} | {clean(old_rows[key][h])} | {clean(row[h])} |")
            for key in old_rows:
                if key not in rows:
                    lines.append(f"*Row removed: {key}.*")
        print(f"## Table {number}\n")
        if not lines:
            print("No change.\n")
            continue
        wrote_head = False
        for line in lines:
            if line.startswith("|"):
                if not wrote_head:
                    print("\n| row | column | old | new |\n|---|---|---:|---:|")
                    wrote_head = True
                print(line)
            else:
                if wrote_head:
                    print()
                    wrote_head = False
                print(line)
        print()


if __name__ == "__main__":
    main()
